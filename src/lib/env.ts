import "dotenv/config";
import { z } from "zod";

const envSchema = z.object({
  NODE_ENV: z.enum(["development", "test", "production"]).default("development"),
  RENDER: z.enum(["true", "false"]).default("false"),
  DATABASE_URL: z.string().min(1).default("postgresql://postgres:postgres@localhost:5432/ppds"),
  REDIS_URL: z.string().min(1).default("redis://localhost:6379"),
  AUTH_SECRET: z.string().min(1).default("development-secret-change-me"),
  APP_URL: z.string().url().default("http://localhost:3000"),
  BUSINESS_TIMEZONE: z.string().min(1).default("Asia/Karachi"),
  DEFAULT_CURRENCY: z.string().min(1).default("PKR"),
  INTEGRATION_MODE: z.enum(["mock", "live"]).default("mock"),
  META_GRAPH_API_VERSION: z.string().min(1).default("v23.0"),
  META_APP_SECRET: z.string().default(""),
  META_ACCESS_TOKEN: z.string().default(""),
  WHATSAPP_PHONE_NUMBER_ID: z.string().default(""),
  WHATSAPP_BUSINESS_ACCOUNT_ID: z.string().default(""),
  WHATSAPP_VERIFY_TOKEN: z.string().default("dev-verify-token"),
  WHATSAPP_PUBLIC_NUMBER: z.string().default("923458197950"),
  AI_PROVIDER: z.string().default("mock"),
  AI_CONFIDENCE_THRESHOLD: z.coerce.number().min(0).max(1).default(0.7),
  FILE_STORAGE_PROVIDER: z.enum(["local", "s3"]).default("local"),
  FILE_STORAGE_PATH: z.string().default("./storage"),
  S3_ENDPOINT: z.string().url().optional().or(z.literal("")),
  S3_REGION: z.string().default("auto"),
  S3_BUCKET: z.string().default(""),
  S3_ACCESS_KEY: z.string().default(""),
  S3_SECRET_KEY: z.string().default(""),
  S3_FORCE_PATH_STYLE: z.coerce.boolean().default(false),
  PUBLIC_ASSET_BASE_URL: z.string().url().optional().or(z.literal("")),
  ENCRYPTION_KEY: z.string().default(""),
  LOG_LEVEL: z.enum(["debug", "info", "warn", "error"]).default("debug"),
});

export const env = envSchema.parse({
  NODE_ENV: process.env.NODE_ENV,
  RENDER: process.env.RENDER,
  DATABASE_URL: process.env.DATABASE_URL,
  REDIS_URL: process.env.REDIS_URL,
  AUTH_SECRET: process.env.AUTH_SECRET,
  APP_URL: process.env.APP_URL,
  BUSINESS_TIMEZONE: process.env.BUSINESS_TIMEZONE,
  DEFAULT_CURRENCY: process.env.DEFAULT_CURRENCY,
  INTEGRATION_MODE: process.env.INTEGRATION_MODE,
  META_GRAPH_API_VERSION: process.env.META_GRAPH_API_VERSION,
  META_APP_SECRET: process.env.META_APP_SECRET,
  META_ACCESS_TOKEN: process.env.META_ACCESS_TOKEN,
  WHATSAPP_PHONE_NUMBER_ID: process.env.WHATSAPP_PHONE_NUMBER_ID,
  WHATSAPP_BUSINESS_ACCOUNT_ID: process.env.WHATSAPP_BUSINESS_ACCOUNT_ID,
  WHATSAPP_VERIFY_TOKEN: process.env.WHATSAPP_VERIFY_TOKEN,
  WHATSAPP_PUBLIC_NUMBER: process.env.WHATSAPP_PUBLIC_NUMBER,
  AI_PROVIDER: process.env.AI_PROVIDER,
  AI_CONFIDENCE_THRESHOLD: process.env.AI_CONFIDENCE_THRESHOLD,
  FILE_STORAGE_PROVIDER: process.env.FILE_STORAGE_PROVIDER,
  FILE_STORAGE_PATH: process.env.FILE_STORAGE_PATH,
  S3_ENDPOINT: process.env.S3_ENDPOINT,
  S3_REGION: process.env.S3_REGION,
  S3_BUCKET: process.env.S3_BUCKET,
  S3_ACCESS_KEY: process.env.S3_ACCESS_KEY,
  S3_SECRET_KEY: process.env.S3_SECRET_KEY,
  S3_FORCE_PATH_STYLE: process.env.S3_FORCE_PATH_STYLE,
  PUBLIC_ASSET_BASE_URL: process.env.PUBLIC_ASSET_BASE_URL,
  ENCRYPTION_KEY: process.env.ENCRYPTION_KEY,
  LOG_LEVEL: process.env.LOG_LEVEL,
});

export type AppEnv = typeof env;
